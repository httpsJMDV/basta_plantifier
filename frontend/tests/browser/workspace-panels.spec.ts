import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

test('workspace panels animate, preserve desktop preference and support mobile navigation',async({page},testInfo)=>{
    const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto('/register');
    await page.getByLabel('Your name',{exact:true}).fill('Panel Explorer');
    await page.getByLabel('Email address').fill('panels-'+randomUUID()+'@example.test');
    const password='Plants-'+randomUUID();
    await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByLabel('Confirm password').fill(password);
    await page.getByRole('button',{name:'Create my account'}).click();
    await page.getByRole('button',{name:'Skip for now'}).click();
    await expect(page).toHaveURL(/workspace/);
    const navigation=page.locator('#main-navigation'),timeline=page.locator('#session-timeline');
    const leftPosition=await page.locator('.navigation-toggle').boundingBox();
    const rightPosition=await page.locator('.timeline-toggle').boundingBox();
    const input=page.getByRole('textbox',{name:'Message PlantifierAI'});
    await expect(input).toHaveCSS('font-size','14px');
    await expect(input).toHaveCSS('height','24px');
    await input.fill(Array(12).fill('A longer botanical question').join('\n'));
    await expect(input).toHaveCSS('height','144px');
    await input.fill('');await expect(input).toHaveCSS('height','24px');
    await expect(timeline).toHaveCSS('transition-duration','0.26s, 0s');
    const oldWidth=(await page.locator('.conversation-pane').boundingBox())!.width;
    await page.getByRole('button',{name:'Hide session timeline'}).click();
    await expect(timeline).toBeHidden();await expect(timeline).toHaveAttribute('inert','');
    expect(await page.locator('.timeline-toggle').boundingBox()).toEqual(rightPosition);
    expect((await page.locator('.conversation-pane').boundingBox())!.width).toBeGreaterThan(oldWidth);
    await page.getByRole('button',{name:'Show session timeline'}).click();await expect(timeline).toBeVisible();
    await page.getByRole('button',{name:'Hide session timeline'}).click();
    await expect(page.getByRole('button',{name:'Show session timeline'})).toBeFocused();
    await page.locator('.navigation-toggle').click();
    await expect(navigation).toBeHidden();await expect(navigation).toHaveAttribute('inert','');
    await expect(page.locator('.main-area')).toHaveCSS('margin-left','0px');
    expect(await page.locator('.navigation-toggle').boundingBox()).toEqual(leftPosition);
    await page.reload();await expect(navigation).toBeHidden();
    await page.getByRole('button',{name:'Expand sidebar'}).click();await expect(navigation).toBeVisible();
    await page.getByRole('button',{name:'Expand Community menu'}).click();
    const community=page.getByRole('navigation',{name:'Community',exact:true});
    await expect(community.getByRole('link',{name:'Stories',exact:true})).toBeVisible();
    await community.getByRole('link',{name:'Stories',exact:true}).click();
    await expect(page).toHaveURL(/community\?tab=stories/);
    await expect(community.getByRole('link',{name:'Stories',exact:true})).toHaveAttribute('aria-current','page');
    await page.getByRole('button',{name:'Collapse Community menu'}).click();
    await expect(community).toBeHidden();
    await page.goto('/settings');
    const photo=Buffer.from(await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=64;canvas.height=64;const context=canvas.getContext('2d')!;context.fillStyle='#547344';context.fillRect(0,0,64,64);return canvas.toDataURL('image/png').split(',')[1]}),'base64');
    await page.getByLabel('Choose profile photo').setInputFiles({name:'portrait.png',mimeType:'image/png',buffer:photo});
    await expect(page.getByText('Preview ready. Save photo to apply it.')).toBeVisible();
    await page.getByRole('button',{name:'Save photo',exact:true}).click();
    await expect(page.locator('.sidebar .avatar img')).toHaveAttribute('src',/^\/media\//);
    await expect(page.locator('.sidebar .avatar img')).toHaveJSProperty('naturalWidth',64);
    await page.reload();await expect(page.locator('.sidebar .avatar img')).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('settings-desktop.png'),fullPage:true});
    await page.getByLabel('Choose profile photo').setInputFiles({name:'large.png',mimeType:'image/png',buffer:Buffer.alloc(5*1024*1024+1)});
    await expect(page.getByRole('alert')).toContainText('up to 5 MB');
    await expect(page.locator('.sidebar .avatar img')).toBeVisible();
    await page.getByRole('button',{name:'Remove',exact:true}).click();
    await expect(page.locator('.sidebar .avatar img')).toHaveCount(0);
    await expect(page.locator('.sidebar .avatar')).toHaveText('PE');
    await page.goto('/workspace');
    await page.screenshot({path:testInfo.outputPath('workspace-desktop.png')});

    await page.setViewportSize({width:390,height:844});await page.reload();
    await expect(navigation).toBeHidden();await expect(timeline).toBeHidden();
    await expect(input).toHaveCSS('font-size','16px');
    await page.getByRole('button',{name:'Open navigation'}).click();await expect(navigation).toBeVisible();
    await page.keyboard.press('Escape');await expect(navigation).toBeHidden();
    await expect(page.getByRole('button',{name:'Open navigation'})).toBeFocused();
    await page.getByRole('button',{name:'Open navigation'}).click();
    await page.getByRole('link',{name:'My Plant Collection',exact:true}).click();
    await expect(page).toHaveURL(/collection/);await expect(navigation).toBeHidden();
    await page.goto('/workspace');
    await page.getByRole('button',{name:'Show session timeline'}).click();await expect(timeline).toBeVisible();
    await page.getByRole('button',{name:'Hide session timeline'}).click();await expect(timeline).toBeHidden();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:testInfo.outputPath('workspace-mobile.png')});
    await page.emulateMedia({reducedMotion:'reduce'});
    await expect(timeline).toHaveCSS('transition-duration','0s');
    await page.goto('/settings');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:testInfo.outputPath('settings-mobile.png'),fullPage:true});
    expect(errors).toEqual([]);
});
